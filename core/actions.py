def _title_tokens(title: str) -> set:
    return {w[:4] for w in re.findall(r"[a-zа-яё0-9_]{3,}", (title or "").lower().replace("ё", "е"))}


def _retitle_guard(old_title: str, new_title: str, fresh_text: str) -> Optional[str]:
    """v4.58: причина отклонить переименование (или None = можно).
    • новое число, которого нет в свежей переписке → модель притянула его из памяти/старой истории
      (кейс 15.09: «3535₽ (кальянная…)» → «3975₽ (пиво…)» по реплике «Кстати можно»);
    • другое ДЕЛО (сохранилось <40% слов названия) → это новая задача, а не уточнение
      (кейс 16.09: «Прийти к Нике на Арбат» → «Отвезти Нику домой на Автозаводскую»)."""
    fresh = (fresh_text or "").lower()
    old_nums = set(re.findall(r"\d{3,}", old_title or ""))
    for n in set(re.findall(r"\d{3,}", new_title or "")) - old_nums:
        if n not in fresh:
            return f"число {n} не из свежей переписки"
    ot, nt = _title_tokens(old_title.lstrip("❓ ")), _title_tokens(new_title)
    if len(ot) >= 3 and len(ot & nt) / len(ot) < 0.4:
        return "другое дело, а не уточнение"
    return None


