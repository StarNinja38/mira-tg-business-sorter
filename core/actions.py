# ── Фикс дат по дню недели (v4.5) ─────────────────────────────────────────────
# Модель извлечения СИСТЕМАТИЧЕСКИ ошибается в арифметике дней недели на 2026 г.
# (репро @tutor_lena: «Ср»→+1 день, «Пт»→+1), причём НЕ исправляется подсказкой в
# промпте — игнорирует переданный день недели и таблицу дат, доверяет своему календарю.
# Поэтому чиним детерминированно: если в тексте назван день недели, «прищёлкиваем»
# дату модели к нужному дню недели ВНУТРИ той же (Пн-Вс) недели — неделю модель почти
# всегда берёт верно, ошибается только в дне внутри неё. Python считает календарь точно.
_WD_ABBR = {"пн": 0, "вт": 1, "ср": 2, "чт": 3, "пт": 4, "сб": 5, "вс": 6}
_WD_PREFIX = {"пон": 0, "вто": 1, "сре": 2, "чет": 3, "пят": 4, "суб": 5, "вос": 6}
_WD_TOKEN_RE = re.compile(
    r"\b(понедельник\w*|вторник\w*|сред[ауые]?\w*|четверг\w*|пятниц\w*|"
    r"суббот\w*|воскресен\w*|пн|вт|ср|чт|пт|сб|вс)\b", re.IGNORECASE)


def _wd_of(word: str):
    w = word.lower()
    if w in _WD_ABBR:
        return _WD_ABBR[w]
    return _WD_PREFIX.get(w[:3])


def _snap_weekday_dates(tasks: list, text: str) -> None:
    """In-place: скорректировать due_date по названному в тексте дню недели. Срабатывает
    ТОЛЬКО когда в тексте есть слово-день-недели и он уверенно сопоставлен задаче (час рядом
    или единственный день в тексте). Иначе дату не трогаем (без ложных срабатываний)."""
    if not tasks or not text:
        return
    wd_hits = [(m.start(), _wd_of(m.group(0))) for m in _WD_TOKEN_RE.finditer(text)]
    wd_hits = [(p, wd) for p, wd in wd_hits if wd is not None]
    if not wd_hits:
        return
    for t in tasks:
        if not isinstance(t, dict):
            continue
        due = t.get("due_date")
        if not isinstance(due, str) or len(due) < 10:
            continue
        try:
            d = datetime.strptime(due[:10], "%Y-%m-%d").date()
        except Exception:
            continue
        target = None
        hour = due[11:13].lstrip("0") if ("T" in due and len(due) >= 13) else ""
        if hour:                                    # пара по часу: час задачи рядом со словом-днём
            hpos = [m.start() for m in re.finditer(r"\b" + re.escape(hour) + r"\b", text)]
            if hpos:
                scored = sorted((min(abs(pos - hp) for hp in hpos), wd) for pos, wd in wd_hits)
                # берём ближайший день недели, ЕСЛИ он в окне И однозначен: либо единственный,
                # либо второй — тот же день, либо заметно (≥6 симв.) дальше. Иначе — неоднозначно,
                # дату не трогаем (bug #7: чужое слово-день рядом с часом → ложный сдвиг).
                if scored and scored[0][0] <= 20 and (
                        len(scored) == 1 or scored[1][1] == scored[0][1]
                        or scored[1][0] - scored[0][0] >= 6):
                    target = scored[0][1]
        if target is None and len(wd_hits) == 1:    # единственный день недели в тексте
            target = wd_hits[0][1]
        if target is None:
            continue
        delta = target - d.weekday()
        if delta == 0:
            continue
        newd = date.fromordinal(d.toordinal() + delta)   # тот же Пн-Вс недельный блок
        t["due_date"] = newd.isoformat() + due[10:]       # время сохраняем
        logger.info(f"weekday-fix: {due} → {t['due_date']} (в тексте назван день недели)")


