def _normalize_due(due: Optional[str]) -> Optional[str]:
    """Ensure a usable due value. A bare time ('18:00') → today's date + time,
    so meeting times are never lost (важно: время должно попадать в задачу)."""
    if not due:
        return None
    due = due.strip()
    import re as _re
    if _re.fullmatch(r"\d{1,2}:\d{2}", due):  # bare HH:MM → attach a date
        from datetime import timedelta as _td
        hh, mm = int(due.split(':')[0]), int(due.split(':')[1])
        now = now_local()
        cand = now.replace(hour=hh, minute=mm, second=0, microsecond=0)
        if cand <= now:            # время уже прошло сегодня → завтра (не вешаем дело в прошлое)
            cand += _td(days=1)
        return cand.strftime("%Y-%m-%dT%H:%M")
    # v4.111: «2026-11-19 18:30» (через пробел, так модель иногда пишет перенос) → «2026-11-19T18:30».
    # Без «T» update_task_calendar молча не двигал событие: 17.11 визит перенесли на четверг 18:30,
    # задача обновилась, а событие и подготовка к встрече остались на вторник 19:30.
    m = _re.fullmatch(r"(\d{4}-\d{2}-\d{2})[ T](\d{1,2}):(\d{2})(?::\d{2})?", due)
    if m:
        return f"{m.group(1)}T{int(m.group(2)):02d}:{m.group(3)}"
    return due


def _diff_day(due_a: Optional[str], due_b: Optional[str]) -> bool:
    """True ТОЛЬКО если оба due заданы и приходятся на РАЗНЫЕ календарные дни.
    Разные дни одного и того же дела (два урока 16-го и 19-го) = РАЗНЫЕ задачи, не дубль.
    Если хоть у одного нет даты — считаем «не разные» (консервативно, прежнее поведение дедупа)."""
    da = str(due_a)[:10] if due_a else None
    db_ = str(due_b)[:10] if due_b else None
    return bool(da and db_ and da != db_)


