def _looks_like_commitment(title: str, user_id: Optional[int], owner_id: Optional[int]) -> bool:
    """Фолбэк-эвристика: обещание = владелец что-то ДОЛЖЕН сделать ДЛЯ человека
    (привезти/отвезти/отдать/вернуть/ответить…). Срабатывает на задачах, привязанных к КОНТАКТУ
    (не self-todo владельца). Не полагаемся только на LLM-флаг is_commitment — он уже ошибался."""
    if not title:
        return False
    if owner_id and user_id == owner_id:   # self-задача владельца — не обещание человеку
        return False
    return bool(_COMMIT_VERB_RE.search(title))


def _category_from_relationship(rel: Optional[str]) -> Optional[str]:
    """Категория задачи от СТАБИЛЬНОЙ роли контакта (а не от разовой классификации сообщения,
    которая у одного человека плавает FRIEND/UNCLEAR/BUSINESS). None → оставить как классифицировано."""
    rel = (rel or "").lower()
    if not rel:
        return None
    if "незнаком" in rel:
        return None  # незнакомец — не FRIEND (иначе ловится подстрокой «знаком»); оставляем категорию сообщения
    # v4.37: словарь расширен под роли из CRM (HR/рекрутер/преподаватель → BUSINESS; одногруппник/бабушка → FRIEND)
    if any(w in rel for w in ("коллег", "клиент", "делов", "партн", "заказчик", "спонсор", "hr", "рекрут",
                              "менеджер", "преподават", "репетит", "работодат", "начальн", "поставщ",
                              "подрядч", "риелт", "агент", "куратор", "рекламодат")):
        return "BUSINESS"
    if any(w in rel for w in ("семь", "приятел", "друг", "девушк", "парень", "мам", "пап",
                              "брат", "сестр", "родств", "жена", "муж", "знаком", "фанат", "подписчик",
                              "одногрупп", "однокурс", "одноклассн", "бабушк", "дедушк", "тёт", "дяд", "племян", "кум")):
        return "FRIEND"
    if "спам" in rel:
        return "SPAM"
    return None  # незнакомец/прочее — оставляем категорию сообщения


