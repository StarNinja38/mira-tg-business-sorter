def _clip_text(s: str, n: int) -> str:
    """Обрезка по границе слова (для карточек), без зависимости от core.vault."""
    s = str(s or "").strip()
    if len(s) <= n:
        return s
    cut = s[:n]
    sp = cut.rfind(" ")
    return (cut[:sp] if sp >= n - 40 else cut).rstrip(" ,;—-") + "…"


def _looks_cancelled(title: str) -> bool:
    """v4.55: модель «отменяет» дело переименованием в отрицание («Не забирать Нику…», «Отменено…») — это не
    новое название, а сигнал закрыть задачу. Кейс 09.09: «Забрать Нику с работы» → «Не забирать Нику — занят в 21:00»."""
