def todoist_section(settings, *, category=None, due=None, is_commitment=False, owner_created=False):
    """v4.46: ОДНО место выбора секции Todoist (раньше владельческие задачи и «➕ В задачу» шли без секции,
    и из 5 секций жили только «Встречи» и «Обещания»). Приоритет: обещание → Обещания; время → Встречи;
    категория → Бизнес/Проверить/Личное; своя задача без категории → Личное."""
    if is_commitment and getattr(settings, "todoist_section_commitment", None):
        return settings.todoist_section_commitment
    if due and "T" in str(due) and getattr(settings, "todoist_section_meeting", None):
        return settings.todoist_section_meeting
    by_cat = {"BUSINESS": getattr(settings, "todoist_section_business", None),
              "UNCLEAR": getattr(settings, "todoist_section_unclear", None),
              "FRIEND": getattr(settings, "todoist_section_friend", None)}.get(category)
    if by_cat:
        return by_cat
    if owner_created:
        return getattr(settings, "todoist_section_friend", None)
    return None


