def _tail(s: str, n: int) -> str:
    """v4.35: обрезка хронологического контекста С ГОЛОВЫ, а не с хвоста. Раньше 7 промптов
    брали `text[:N]` — при длинном треде (или память впереди) в промпт не попадали САМЫЕ СВЕЖИЕ
    сообщения: судья не видел «Скинул», извлечение — «Вт 19 / Ср 19». Режем по границе строки."""
    s = s or ""
    if len(s) <= n:
        return s
    cut = s[-n:]
    nl = cut.find("\n")
    return cut[nl + 1:] if 0 <= nl < 200 else cut


