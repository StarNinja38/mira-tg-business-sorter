async def update_todoist_task(token: str, task_id: str, due_date: Optional[str], content: Optional[str] = None) -> bool:
    """Обновить срок и/или (v4.35) текст задачи в Todoist. due_date=None → только content."""
    url = f"https://api.todoist.com/api/v1/tasks/{task_id}"
    payload: dict = {}
    if content:
        payload["content"] = content[:500]
    if due_date and "T" in due_date:     # полный datetime → due_datetime со смещением tz
        payload["due_datetime"] = _todoist_due_datetime(due_date)
    elif due_date and ":" in due_date:   # голое время «15:00» → due_string (Todoist парсит в tz аккаунта)
        payload["due_string"] = due_date
    elif due_date:
        payload["due_date"] = due_date
    if not payload:
        return False
    try:
        async with aiohttp.ClientSession(timeout=aiohttp.ClientTimeout(total=20)) as session:
            async with session.post(
                url, json=payload,
                headers={"Authorization": f"Bearer {token}"},
            ) as resp:
                if resp.status == 404:   # C8: задача уже закрыта/удалена в Todoist — sync-петля переведёт её в synced
                    logger.warning(f"Todoist update: task {task_id} not found (404) — closed/deleted on Todoist side")
                elif resp.status != 200:
                    logger.warning(f"Todoist update error {resp.status}: {(await resp.text())[:200]}")
                return resp.status == 200
    except Exception as exc:
        logger.warning(f"Todoist update request failed: {exc}")
        return False


DEDUP_SYSTEM = """Ты решаешь, дублирует ли НОВАЯ задача одну из уже открытых задач того же человека.
Дубль = про ТО ЖЕ дело/встречу/поездку/просьбу, даже если формулировки разные или уточнились время/детали
(напр. «Поехать в вуз» и «Встретиться в 8:20 для поездки в вуз» — это ОДНО). Разные дела с одним человеком
(поездка в вуз и поездка в Шанхай) — НЕ дубль. Отвечай строго JSON без markdown."""

DEDUP_USER = """Новая задача: «{title}»
{desc}
Уже открытые задачи этого человека:
{existing}

Это дубль (то же дело) одной из существующих? Верни JSON: {{"dup_index": <номер из списка или -1>}}"""


async def _dedup_judge(client: AsyncAnthropic, model: str, title: str, desc: str, open_tasks: list) -> Optional[int]:
    """Семантический судья: кандидат vs все открытые задачи человека. Возвращает индекс дубля или None.
    Надёжнее тег-матча/нечёткого титула — ловит перефраз и уточнения."""
    if not open_tasks:
        return None
    listing = "\n".join(
        f"{i}. {t['title']}" + (f" [тема: {t['topic']}]" if t.get("topic") else "")
        for i, t in enumerate(open_tasks)
    )
    try:
        prompt = DEDUP_USER.format(
            title=title, desc=(f"Контекст: {desc[:200]}" if desc else ""), existing=listing
        )
        resp = await llm.create(client, 
            model=model, max_tokens=80, system=DEDUP_SYSTEM,
            messages=[{"role": "user", "content": prompt}],
        )
        await _rec(model, resp.usage, "dedup_judge")
        idx = loads_loose(_llm_text(resp)).get("dup_index", -1)
        if isinstance(idx, int) and 0 <= idx < len(open_tasks):
            return idx
    except Exception as exc:
        logger.warning(f"dedup judge skipped: {type(exc).__name__}: {exc}")
    return None


