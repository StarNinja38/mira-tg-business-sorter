async def _check_tasks_done_batch(client: AsyncAnthropic, model: str,
                                  tasks: list, conversation: str) -> set:
    """Один вызов на ВСЕ открытые задачи (вместо одного на задачу). Строгая логика
    (DONE_BATCH_SYSTEM). Возвращает множество индексов выполненных задач. При сбое — пусто
    (ничего не закрываем — безопасно).
    P1.2 плана 07/2026: Haiku вместо Sonnet — направление безопасное (результат = только
    ПРЕДЛОЖЕНИЕ кнопкой, закрывает владелец; ложный пропуск = задача просто остаётся открытой)."""
    if not tasks:
        return set()
    from config import settings as _s
    model = _s.anthropic_model  # haiku
    task_list = "\n".join(
        f"{i}. {t['title']}" + (f" [тема: {t['topic']}]" if t.get("topic") else "")
        for i, t in enumerate(tasks))
    try:
        resp = await llm.create(client, 
            model=model, max_tokens=300, system=DONE_BATCH_SYSTEM,
            messages=[{"role": "user", "content": DONE_BATCH_USER.format(
                task_list=task_list, conversation=_tail(conversation, 2500))}],
        )
        await _rec(model, resp.usage, "done_check_batch")
        idxs = loads_loose(_llm_text(resp)).get("done", [])
        return {i for i in idxs if isinstance(i, int) and 0 <= i < len(tasks)}
    except Exception as exc:
        logger.warning(f"done batch skipped: {type(exc).__name__}: {exc}")
        return set()


async def auto_close_tasks(client, model, db, todoist_token, notion_token,
                           user_id, username, conversation, bot=None, owner_id=None,
                           over_budget=False) -> int:
    """P0 (доверие к данным): LLM-судья ДЕТЕКТИРУЕТ вероятно выполненные задачи, но больше
    НЕ закрывает их сам — только ПРЕДЛАГАЕТ владельцу закрыть кнопкой. Закрытие происходит
    исключительно по нажатию ✅ (cb_done / `td:`). Это снимает риск «бот молча закрыл не то»
    (кейс @tutor_lena) — система перестаёт автономно менять статус твоих задач."""
    if over_budget or not db:
        return 0
    if not (bot and owner_id):
        return 0  # некому предлагать — без владельца молча ничего не трогаем
    from db import get_open_tasks_for_user, can_notify as _can_notify, log_notification as _log_notif
    from core.topics import send_owner
    from aiogram.types import InlineKeyboardMarkup, InlineKeyboardButton
    open_tasks = await get_open_tasks_for_user(db, user_id)
    if not open_tasks:
        return 0
    # P1.2: done-судья на Haiku — безопасное направление (только ПРЕДЛАГАЕТ кнопкой, закрытие за
    # владельцем; ложный пропуск = задача просто остаётся открытой). Sonnet тут был −$1.6/мес.
    from config import settings as _cfg
    done_idx = await _check_tasks_done_batch(client, _cfg.anthropic_model, open_tasks, conversation)  # 1 вызов вместо N
    suggested = 0
    for i, t in enumerate(open_tasks):
        if i not in done_idx:
            continue
        if (t.get("title") or "").lstrip().startswith("❓"):
            continue  # ❓-заготовка (дело без уточнения) — не предлагаем закрывать (кейс @tutor_lena)
        # НЕ глушим задачу надолго: «сделано» меняется день в день, а предложение приходит по
        # НОВЫМ признакам в переписке → пусть спросит снова, если они появятся. От спама в тот
        # же день защищает суточный guard timeclose:{id} ниже.
        # один раз в сутки на задачу (общий guard timeclose:{id} — без спама)
        if not await _can_notify(db, user_id, f"timeclose:{t['id']}", cooldown_minutes=24 * 60):
            continue
        from core.topics import snooze_row
        kb = InlineKeyboardMarkup(inline_keyboard=[[
            InlineKeyboardButton(text="✅ Да, закрыть", callback_data=f"td:{t['id']}", style="success"),
            InlineKeyboardButton(text="↩️ Открыта", callback_data=f"keepopen:{t['id']}", style="primary"),
        ], snooze_row()])
        await send_owner(bot, owner_id, "tasks",
                         f"🤔 <b>Похоже, это уже сделано</b>\n📌 {t['title']}\n<i>сужу по переписке с @{username} — закрыть?</i>",
                         parse_mode="HTML", reply_markup=kb)
        await _log_notif(db, user_id, f"timeclose:{t['id']}")
        suggested += 1
        logger.info(f"Auto-close SUGGESTED (not closed) '{t['title']}' for @{username}")
    return suggested


# ── Гибрид-закрытие задач по ВРЕМЕНИ (детерминированно, без LLM) ──────────────
TIME_CLOSE_GRACE_MIN = 30      # реагировать через 30 мин после времени задачи
TIME_CLOSE_WINDOW_HRS = 6      # не трогать слишком старые (защита при первом проходе/рестарте)
# Признак опоздания/переноса в свежей переписке → не закрывать молча, а спросить.
_RESCHEDULE_RE = re.compile(
    r"(не успе|перенес|перенёс|попозже|\bпозже\b|давай завтра|давай в |опозда|задерж|"
    r"выезжаю|ещё не|еще не|пока не|сдвин|не сегодня|в другой раз)", re.I)


def _is_multi_action(title: str) -> bool:
    """Задача из нескольких действий («отвезти И забрать», «X и забрать/заехать/вернуть»):
    по времени НЕ авто-закрываем (один этап мог остаться), а спрашиваем."""
    t = (title or "").lower()
    return bool(re.search(r"\bи\s+(забрать|заехать|вернуть|привезти|отвезти|купить|оплатить|заплатить|захватить)", t))


async def time_settle_tasks(bot, db, settings) -> int:
    """Гибрид (по выбору владельца): для открытых задач с КОНКРЕТНЫМ временем, когда время прошло
    на +30 мин — нет признака опоздания/переноса и одно действие → авто-закрыть; иначе (опоздание/
    перенос или многосоставная задача) → спросить владельца кнопками ✅/📅 (один раз на задачу).
    Детерминированно, без LLM — не зависит от флаки-судьи. Время задачи должно быть верным (см. UPDATE-фикс)."""
    from db import (get_all_open_timed_tasks, mark_sync_done_by_id, can_notify,
                    log_notification, vault_get_context)
    from core.sync import complete_todoist_task
    from core.topics import send_owner
    from core.util import now_local
    try:
        tasks = await get_all_open_timed_tasks(db)
    except Exception as exc:
        logger.debug(f"time_settle: list failed: {exc}")
        return 0
    if not tasks:
        return 0
    now = now_local()
    acted = 0
    for t in tasks:
        due = _normalize_due(t.get("due_date"))
        if not due or "T" not in due:
            continue
        try:
            due_dt = datetime.fromisoformat(due)
        except Exception:
            continue
        if due_dt.tzinfo is None:
            due_dt = due_dt.replace(tzinfo=now.tzinfo)
        overdue_min = (now - due_dt).total_seconds() / 60.0
        if overdue_min < TIME_CLOSE_GRACE_MIN or overdue_min > 24 * 60:
            continue  # ещё рано ИЛИ старше суток (стейл — не трогаем)
        uid, sid, title = t["user_id"], t["id"], t["title"]
        # один раз на задачу (cooldown сутки). fix #3: свой неймспейс timeask: (по времени) —
        # раньше общий timeclose: с auto_close глушил его evidence-based предложение по переписке.
        if not await can_notify(db, uid, f"timeask:{sid}", cooldown_minutes=24 * 60):
            continue
        # старше окна авто-закрытия (6ч, напр. простой/ночь) → не закрывать молча, а спросить
        ask = _is_multi_action(title) or overdue_min > TIME_CLOSE_WINDOW_HRS * 60
        if not ask:
            try:
                conv = await vault_get_context(db, uid, limit=6) or ""
            except Exception:
                conv = ""
            if _RESCHEDULE_RE.search(conv):
                ask = True  # опоздание/перенос → не закрывать молча
        if ask:
            from aiogram.types import InlineKeyboardMarkup, InlineKeyboardButton
            kb = InlineKeyboardMarkup(inline_keyboard=[[
                InlineKeyboardButton(text="✅ Сделал", callback_data=f"td:{sid}"),
                InlineKeyboardButton(text="📅 Перенести", callback_data=f"snm:{sid}"),
            ]])
            await send_owner(bot, settings.owner_user_id, "tasks",
                             f"⏰ Ну что, сделал? <b>{title}</b>",
                             parse_mode="HTML", reply_markup=kb)
            logger.info(f"Time-ask owner about '{title}' (overdue {int(overdue_min)}m, multi/reschedule)")
        else:
            if settings.todoist_api_token and t["todoist_id"]:
                await complete_todoist_task(settings.todoist_api_token, t["todoist_id"])
            await mark_sync_done_by_id(db, sid)
            await _delete_task_calendar_event(db, t)  # гасим осиротевшее событие календаря
