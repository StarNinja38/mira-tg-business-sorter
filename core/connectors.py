def _browser_ready() -> bool:
    from core import browser
    return browser.available()


def ready(settings, cid: str) -> bool:
    return bool(_READY[cid](settings))


async def enabled(db, settings, cid: str) -> bool:
    from db import get_setting
    return ready(settings, cid) and await get_setting(db, f"conn:{cid}") != "off"


async def state(db, settings) -> list:
    from db import get_setting
    out = []
    for c in CONNECTORS:
        is_ready = ready(settings, c["id"])
        off = await get_setting(db, f"conn:{c['id']}") == "off"
        out.append({**c, "ready": is_ready, "on": is_ready and not off, "need": "" if is_ready else _NEEDS.get(c["id"], "")})
    return out


async def toggle(db, settings, cid: str, on: bool) -> bool:
    """Включить или выключить. False — выключить нельзя или доступа нет."""
    from db import set_setting
    c = _BY_ID.get(cid)
    if not c or c.get("system") or not ready(settings, cid):
        return False
    await set_setting(db, f"conn:{cid}", "on" if on else "off")
    return True
